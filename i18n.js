// Missing German? The English text is shown instead, so nothing ever breaks.
let LANG = 'en';
export const lang = () => LANG;
export const loc = () => (LANG === 'de' ? 'de-DE' : 'en-GB');
export function setLang(l) {
  LANG = l === 'de' ? 'de' : 'en';
  document.documentElement.lang = LANG;
  document.title = t("Dragon's Hoard");
}
export function t(s, v) {
  let out = (LANG === 'de' && DE[s]) || s;
  if (v) out = out.replace(/\{(\w+)\}/g, (m, k) => (v[k] ?? m));
  return out;
}
/** Plurals: tn(3, '{n} expense', '{n} expenses') */
export const tn = (n, one, many, v = {}) => t(n === 1 ? one : many, { n, ...v });

